#!/usr/bin/env node
// Builds public/wp/theme.css (+ icon fonts) from the extracted old-site design assets.
// Usage: EXPORT_DIR=../export SUPABASE_URL=... SUPABASE_ANON_KEY=... node scripts/build-theme.mjs
// The export directory is never committed; only the generated, public CSS/fonts are.
import fs from "node:fs";
import path from "node:path";

const EXPORT_DIR = path.resolve(process.env.EXPORT_DIR || "../export");
const OUT = path.resolve("public/wp");
const cssDir = path.join(EXPORT_DIR, "design/css");
const fontDir = path.join(EXPORT_DIR, "design/fonts");

const byName = Object.fromEntries(
  fs.readdirSync(cssDir).map((f) => [f.replace(/^[0-9a-f]{8}_/, ""), path.join(cssDir, f)]),
);
const styleMin = fs.readdirSync(cssDir).filter((f) => f.endsWith("_style.min.css"));
// two different style.min.css files: OceanWP theme (large) and ocean-modal-window (small)
const sized = styleMin.map((f) => [f, fs.statSync(path.join(cssDir, f)).size]).sort((a, b) => b[1] - a[1]);
const oceanStyle = path.join(cssDir, sized[0][0]);
const modalStyle = path.join(cssDir, sized[1][0]);

const index = fs.readFileSync(path.join(EXPORT_DIR, "html/index.html"), "utf8");
const head = index.slice(0, index.indexOf("<body"));
const inlineStyles = [...head.matchAll(/<style([^>]*)>([\s\S]*?)<\/style>/g)].map((m) => ({ attrs: m[1], css: m[2] }));
const inl = (pred) => inlineStyles.filter(pred).map((s) => s.css).join("\n");

// Order mirrors the <head> of the old site (product + checkout extras merged in place).
const parts = [
  ["inline:wp-core", inl((s) => /wp-img-auto|wp-emoji|wp-block-library|classic-theme|global-styles/.test(s.attrs))],
  ["photoswipe.min.css", byName["photoswipe.min.css"]],
  ["default-skin.min.css", byName["default-skin.min.css"]],
  ["select2.css", byName["select2.css"]],
  ["inline:woocommerce", inl((s) => /woocommerce-inline/.test(s.attrs))],
  ["woo-mini-cart.min.css", byName["woo-mini-cart.min.css"]],
  ["all.min.css", byName["all.min.css"]],
  ["simple-line-icons.min.css", byName["simple-line-icons.min.css"]],
  ["oceanwp style.min.css", oceanStyle],
  ["hamburgers.min.css", byName["hamburgers.min.css"]],
  ["collapse.css", byName["collapse.css"]],
  ["sticky-header style.css", byName["style.css"]],
  ["elementor-icons.min.css", byName["elementor-icons.min.css"]],
  ["frontend.min.css", byName["frontend.min.css"]],
  ["post-1136.css", byName["post-1136.css"]],
  ["post-396.css", byName["post-396.css"]],
  // post-298.css (聯絡我們) was missing from the export; fetched once from the live site (read-only) into scripts/assets
  ["post-298.css", byName["post-298.css"] || path.resolve("scripts/assets/post-298.css")],
  ["woocommerce.min.css", byName["woocommerce.min.css"]],
  ["woo-star-font.min.css", byName["woo-star-font.min.css"]],
  ["woo-quick-view.min.css", byName["woo-quick-view.min.css"]],
  ["woo-floating-bar.min.css", byName["woo-floating-bar.min.css"]],
  ["perfect-scrollbar.css", byName["perfect-scrollbar.css"]],
  ["ocean-modal-window style.min.css", modalStyle],
  ["fontawesome.min.css", byName["fontawesome.min.css"]],
  ["regular.min.css", byName["regular.min.css"]],
  ["solid.min.css", byName["solid.min.css"]],
  ["brands.min.css", byName["brands.min.css"]],
  ["inline:theme", inl((s) => !/wp-img-auto|wp-emoji|wp-block-library|classic-theme|global-styles|woocommerce-inline/.test(s.attrs))],
  ["animations.min.css", byName["animations.min.css"]],
];

async function mediaMap() {
  const url = process.env.SUPABASE_URL, key = process.env.SUPABASE_ANON_KEY;
  if (!url || !key) return {};
  const r = await fetch(`${url}/rest/v1/media_url_map?select=old_url,new_url`, {
    headers: { apikey: key, "Accept-Profile": "site_palacetw" },
  });
  const rows = await r.json();
  return Object.fromEntries(rows.map((x) => [x.old_url, x.new_url]));
}

const map = await mediaMap();
const usedFonts = new Set();
let out = "/* Generated by scripts/build-theme.mjs from the original OceanWP/Elementor/WooCommerce styles. */\n";
for (const [label, src] of parts) {
  if (!src) { console.warn("missing", label); continue; }
  let css = label.startsWith("inline:") ? src : fs.readFileSync(src, "utf8");
  css = css.replace(/\/\*# sourceURL=[^*]*\*\//g, "");
  // woo-floating-bar.min.css was only enqueued on product pages; keep its body offset scoped to them
  if (label === "woo-floating-bar.min.css") css = css.replace(/body\{margin-bottom:45px\}/g, "body:has(.wpb.single-product){margin-bottom:45px}");
  // fonts -> /wp/fonts/<basename>
  css = css.replace(/url\((['"]?)([^'")]+\.(?:woff2?|ttf|eot|svg|otf)(?:[?#][^'")]*)?)\1\)/g, (m, q, u) => {
    if (/^data:/.test(u) || /wp-content\/uploads/.test(u)) return m;
    const base = u.split(/[?#]/)[0].split("/").pop();
    usedFonts.add(base);
    const suffix = u.includes("#") && !u.includes("?#") ? "#" + u.split("#")[1] : "";
    return `url("/wp/fonts/${base}${suffix}")`;
  });
  // media -> Supabase storage
  css = css.replace(/url\((['"]?)(https?:\/\/palacetwshop\.com\/wp-content\/uploads\/[^'")]+)\1\)/g, (m, q, u) => {
    const k = u.replace(/^http:/, "https:");
    return map[k] ? `url("${map[k]}")` : m;
  });
  // body.<class> selectors -> wrapper .wpb.<class> (body classes live on the wrapper div)
  css = css.replace(/(^|[^\w-])body\.(?=[A-Za-z_-])/g, "$1.wpb.");
  out += `\n/* ---- ${label} ---- */\n${css}\n`;
}
out = responsiveBackgrounds(out);
fs.mkdirSync(path.join(OUT, "fonts"), { recursive: true });
fs.writeFileSync(path.join(OUT, "theme.css"), out);
let copied = 0;
for (const f of usedFonts) {
  if (/\.(eot|svg)$/.test(f)) continue;
  const p = path.join(fontDir, f);
  if (fs.existsSync(p)) { fs.copyFileSync(p, path.join(OUT, "fonts", f)); copied++; }
  else console.warn("font not found", f);
}
console.log(`theme.css ${(out.length / 1024).toFixed(0)}KB, fonts copied ${copied}`);

/**
 * Large Elementor section backgrounds → responsive WebP variants (bucket v/<w>/…, see scripts/media-variants.mjs):
 * 1440 px by default, 960 px on phones, the stored 2000 px image only on screens wider than 1440 px.
 * Only images listed here are known to have a 1440 variant (stored width > 1440).
 */
function responsiveBackgrounds(css) {
  const BIG = ["uploads/2021/04/01home-scaled.webp"];
  let extra = "";
  for (const file of BIG) {
    const re = new RegExp(`([^{}]+)\\{([^{}]*?)background-image:url\\("([^"]*/site-palacetw/)${file.replace(/[.]/g, "\\.")}"\\)`, "g");
    css = css.replace(re, (m, sel, pre, base) => {
      const v = (w) => `${base}v/${w}/${file}`;
      extra += `@media (max-width:767px){${sel}{background-image:url("${v(960)}");}}@media (min-width:1441px){${sel}{background-image:url("${base}${file}");}}`;
      return `${sel}{${pre}background-image:url("${v(1440)}")`;
    });
  }
  return extra ? `${css}\n/* ---- responsive backgrounds ---- */\n${extra}\n` : css;
}
