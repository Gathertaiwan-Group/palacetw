-- Stage: admin + MCP. Extra WooCommerce tables (empty until the private DB backup is imported in stage 3),
-- helper functions used by the admin/MCP service layer. Everything is schema-qualified to site_palacetw.

-- WooCommerce refunds (shop_order_refund)
create table if not exists site_palacetw.order_refunds (
  id            bigint generated by default as identity (start with 100000) primary key,
  order_id      bigint not null references site_palacetw.orders(id) on delete cascade,
  amount        numeric(12,2) not null default 0,
  reason        text not null default '',
  refunded_by   text,
  line_items    jsonb not null default '[]'::jsonb,
  created_at    timestamptz not null default now()
);
create index if not exists order_refunds_order_idx on site_palacetw.order_refunds(order_id);

-- WooCommerce shipping zones / methods (woocommerce_shipping_zones, _zone_locations, _zone_methods)
create table if not exists site_palacetw.shipping_zones (
  id          bigint generated by default as identity (start with 100000) primary key,
  name        text not null,
  zone_order  int not null default 0,
  locations   jsonb not null default '[]'::jsonb,   -- [{"type":"country","code":"TW"}]
  created_at  timestamptz not null default now()
);
create table if not exists site_palacetw.shipping_methods (
  id           bigint generated by default as identity (start with 100000) primary key,
  zone_id      bigint references site_palacetw.shipping_zones(id) on delete cascade,
  method_id    text not null,                        -- flat_rate / free_shipping / local_pickup
  title        text not null default '',
  enabled      boolean not null default true,
  method_order int not null default 0,
  settings     jsonb not null default '{}'::jsonb
);
create index if not exists shipping_methods_zone_idx on site_palacetw.shipping_methods(zone_id);

-- WooCommerce tax rates (woocommerce_tax_rates)
create table if not exists site_palacetw.tax_rates (
  id         bigint generated by default as identity (start with 100000) primary key,
  country    text not null default '',
  state      text not null default '',
  rate       numeric(8,4) not null default 0,
  name       text not null default '',
  priority   int not null default 1,
  compound   boolean not null default false,
  shipping   boolean not null default true,
  tax_class  text not null default '',
  rate_order int not null default 0
);

-- plugin options (wp_options rows belonging to plugins: wordfence, rank math, pixelyoursite …), never public
create table if not exists site_palacetw.plugin_options (
  option_name  text primary key,
  plugin       text,
  value        jsonb not null,
  autoload     boolean not null default true,
  updated_at   timestamptz not null default now()
);

do $$
declare t text;
begin
  foreach t in array array['order_refunds','shipping_zones','shipping_methods','tax_rates','plugin_options'] loop
    execute format('alter table site_palacetw.%I enable row level security', t);
    execute format('grant all on site_palacetw.%I to service_role', t);
    execute format('revoke insert, update, delete, truncate on site_palacetw.%I from anon, authenticated', t);
    execute format('grant select on site_palacetw.%I to authenticated', t);
    execute format('drop policy if exists admin_read on site_palacetw.%I', t);
    execute format('create policy admin_read on site_palacetw.%I for select to authenticated using ((select site_palacetw.is_admin()))', t);
  end loop;
end $$;
grant usage, select on all sequences in schema site_palacetw to service_role;

-- recount published objects per term (WordPress _update_post_term_count)
create or replace function site_palacetw.recount_terms()
returns void language sql security definer set search_path = '' as $$
  update site_palacetw.terms t set count = coalesce(c.n, 0)
  from (
    select tt.id, (select count(*) from site_palacetw.term_relationships r
                   join site_palacetw.posts p on p.id = r.object_id
                   where r.term_id = tt.id and p.status = 'publish')::int as n
    from site_palacetw.terms tt
  ) c
  where c.id = t.id and t.count is distinct from coalesce(c.n, 0);
$$;
revoke all on function site_palacetw.recount_terms() from public, anon, authenticated;
grant execute on function site_palacetw.recount_terms() to service_role;

-- scheduled posts: flip status future -> publish once the publish date has passed
create or replace function site_palacetw.publish_due()
returns int language plpgsql security definer set search_path = '' as $$
declare n int;
begin
  update site_palacetw.posts set status = 'publish', modified_at = now()
   where status = 'future' and published_at is not null and published_at <= now();
  get diagnostics n = row_count;
  if n > 0 then
    perform site_palacetw.recount_terms();
    insert into site_palacetw.audit_log(actor, actor_type, action, entity_type, after)
    values ('scheduler', 'system', 'post.publish_scheduled', 'post', jsonb_build_object('count', n));
  end if;
  return n;
end $$;
revoke all on function site_palacetw.publish_due() from public, anon, authenticated;
grant execute on function site_palacetw.publish_due() to service_role;

-- identity sequences must stay above every existing ID (legacy WordPress IDs are kept) and never below
-- their declared start value (100000), so new rows never collide with IDs imported later in stage 3.
do $$
declare r record; mx bigint; cur bigint; st bigint;
begin
  for r in select c.relname tbl, a.attname col, pg_get_serial_sequence('site_palacetw.'||c.relname, a.attname) seq
           from pg_attribute a join pg_class c on c.oid = a.attrelid join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'site_palacetw' and a.attidentity <> '' loop
    continue when r.seq is null;
    execute format('select max(%I) from site_palacetw.%I', r.col, r.tbl) into mx;
    select s.last_value, s.start_value into cur, st from pg_sequences s where s.schemaname||'.'||s.sequencename = r.seq;
    perform setval(r.seq, greatest(coalesce(mx, 0), coalesce(cur, 0), st - 1, 1));
  end loop;
end $$;
