-- site_palacetw: data model for 台灣宮廷酒廠 (WordPress + WooCommerce migration)
-- Every object is schema-qualified to site_palacetw. Old WordPress IDs are kept as primary keys;
-- identity columns start at 100000 so new rows never collide with legacy IDs.

-- ---------- helpers ----------
create table if not exists site_palacetw.admins (
  user_id     uuid primary key,              -- auth.users.id
  email       text not null unique,
  role        text not null default 'administrator' check (role in ('administrator','shop_manager','editor')),
  created_at  timestamptz not null default now()
);

create or replace function site_palacetw.is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from site_palacetw.admins a where a.user_id = (select auth.uid()));
$$;

create or replace function site_palacetw.touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end $$;

