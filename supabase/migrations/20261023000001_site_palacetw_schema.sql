-- ---------- posts: post / page / product / ocean_modal_window / any CPT ----------
create table if not exists site_palacetw.posts (
  id               bigint generated by default as identity (start with 100000) primary key, -- wp ID
  post_type        text not null,
  status           text not null default 'draft' check (status in ('publish','draft','pending','private','future','trash')),
  slug             text not null,
  path             text,                  -- URL path on the old site, e.g. /product/xxx/
  title            text not null default '',
  content          text not null default '',
  excerpt          text not null default '',
  author_id        bigint references site_palacetw.authors(id) on delete set null,
  parent_id        bigint references site_palacetw.posts(id) on delete set null,
  menu_order       int not null default 0,
  template         text not null default '',
  format           text not null default 'standard',
  sticky           boolean not null default false,
  comment_status   text not null default 'closed',
  ping_status      text not null default 'closed',
  featured_media_id bigint,
  password         text,                  -- never exposed publicly (column privilege revoked below)
  published_at     timestamptz,           -- post_date_gmt
  date_local       timestamp,             -- post_date (site local time)
  modified_at      timestamptz,
  seo              jsonb not null default '{}'::jsonb,   -- Rank Math: title, description, robots, canonical, og
  meta             jsonb not null default '{}'::jsonb,
  old_url          text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  unique (post_type, slug)
);
create index if not exists posts_type_status_idx on site_palacetw.posts(post_type, status, published_at desc);
create index if not exists posts_parent_idx on site_palacetw.posts(parent_id);
create index if not exists posts_author_idx on site_palacetw.posts(author_id);
create index if not exists posts_path_idx on site_palacetw.posts(path);

create table if not exists site_palacetw.term_relationships (
  object_id   bigint not null references site_palacetw.posts(id) on delete cascade,
